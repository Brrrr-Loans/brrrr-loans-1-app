CREATE TABLE IF NOT EXISTS public.document_statuses (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  organization_id uuid NULL,
  org_id bigint NULL,
  code text NOT NULL,
  label text NOT NULL,
  color text NULL,
  display_order integer NOT NULL DEFAULT 0,
  is_active boolean NOT NULL DEFAULT true,
  is_terminal boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  is_default boolean NOT NULL DEFAULT false,
  CONSTRAINT document_statuses_pkey PRIMARY KEY (id),
  CONSTRAINT document_status_org_id_fkey FOREIGN KEY (org_id)
    REFERENCES auth_clerk_orgs(id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS document_statuses_code_global_uniq
  ON public.document_statuses (code) WHERE organization_id IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS document_statuses_code_org_uniq
  ON public.document_statuses (organization_id, code) WHERE organization_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS document_statuses_org_display_idx
  ON public.document_statuses (org_id, display_order, label);
CREATE UNIQUE INDEX IF NOT EXISTS idx_document_statuses_single_default
  ON public.document_statuses (is_default) WHERE is_default = true;

ALTER TABLE public.document_statuses ENABLE ROW LEVEL SECURITY;

